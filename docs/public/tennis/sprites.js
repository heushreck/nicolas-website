// Pre-computed horizontal colour runs per sprite: [colour, x, y, length][]
const RUNS = {};
function runs(name) {
  let r = RUNS[name];
  if (r) return r;
  const rows = SPRITES[name];
  if (!rows) throw new Error(`Unknown sprite: ${name}`);
  r = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      let len = 1;
      while (x + len < row.length && row[x + len] === c) len++;
      if (c !== '.') r.push([PALETTE[c], x, y, len]);
      x += len;
    }
  });
  RUNS[name] = r;
  return r;
}

export function spriteSize(name) {
  const rows = SPRITES[name];
  if (!rows) throw new Error(`Unknown sprite: ${name}`);
  return { w: rows[0].length, h: rows.length };
}

export function drawSprite(ctx, name, x, y, scale = 1, flip = false) {
  const { w } = spriteSize(name);
  const ox = Math.round(x), oy = Math.round(y);
  const s = Math.max(1, Math.round(scale));
  for (const [col, rx, ry, len] of runs(name)) {
    const px = flip ? w - rx - len : rx;
    ctx.fillStyle = col;
    ctx.fillRect(ox + px * s, oy + ry * s, len * s, s);
  }
}

export function spriteCanvas(name, scale = 4, flip = false) {
  const { w, h } = spriteSize(name);
  const s = Math.max(1, Math.round(scale));
  const canvas = document.createElement('canvas');
  canvas.width = w * s;
  canvas.height = h * s;
  canvas.style.imageRendering = 'pixelated';
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  drawSprite(ctx, name, 0, 0, s, flip);
  return canvas;
}

const URL_CACHE = new Map();
export function spriteDataURL(name, scale = 4, flip = false) {
  const key = `${name}|${scale}|${flip ? 1 : 0}`;
  let url = URL_CACHE.get(key);
  if (!url) {
    url = spriteCanvas(name, scale, flip).toDataURL('image/png');
    URL_CACHE.set(key, url);
  }
  return url;
}
