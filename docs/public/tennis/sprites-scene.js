// Same format as sprites.js: every sprite is an array of equal-length strings; each char is a PALETTE key and
// '.' is transparent. Outlines are near-black 'k'. Pure data, no DOM code.
//
// Notes for placing things (x, y are pixel columns/rows inside the sprite):
// - friend1a/b, friend2a/b, friend3a/b: 32x40 like the players, face RIGHT, shoe/foot outline on row 39 in both frames.
//   'a' = arms up, 'b' = arms out with a 1px knee-bend squash (head/torso 1px lower), so the loop bounces.
// - Seamless horizontal tiles: wave1/wave2, crowd1/crowd2, banner (repeat every 32 / 64 / 64 px).
//   wave*: bottom row is solid sea blue #4aa6f0 ('i'); fill the sea below the tile with that colour.
//   crowd*: rows 8-23 are fully opaque (stand + people); rows 0-7 are heads, raised arms, hats and flags over transparency.
// - Ground contact on the bottom row: palm* (trunk base x12-19, centre ~x15.5), parasol (pole x19-20),
//   sandcastle, tomb, umpire* (chair feet x2-5 and x16-19), scoreboard, dust*, puddle*, friends, ballkid*, crab*.
// - discoball*: string hangs from the top row at x8. bolt*: top at x5-8 on row 0, tip at x3 on row 29.
// - scoreboard: blank dark face (#26263a) at x4-35, y4-13 inside a 1px 'k' border — the page writes digits there.
// - umpire1 looks LEFT, umpire2 looks RIGHT; only the face changes (eyes, nose, moustache), chair and body are identical.
//   The umpire faces the viewer from the net post, so the chair reads in the side-on court view.
// - star, sparkle-like 'flash', tear and halo have no outline or a thin one; apply page opacity as needed.
//
